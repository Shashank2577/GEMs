/**
 * Security headers (002/FR-050), shared by the API (Node + Worker, apps/api/src/middleware/security.ts) and the web
 * build (apps/web/vite.config.ts writes `dist/_headers` for Cloudflare static assets). Pure + WebCrypto only.
 *
 * - `X-Content-Type-Options: nosniff`, `X-Frame-Options: DENY` and `Referrer-Policy: no-referrer` on every response.
 *   `no-referrer` (stricter than the spec's original `strict-origin-when-cross-origin`) also keeps the secret in
 *   `/invite/<token>` and `/reset-password/<token>` URLs out of the Referer sent to Google Fonts or any link target.
 * - `Strict-Transport-Security` only on https responses (browsers ignore it over http anyway).
 * - A Content-Security-Policy for the SPA document whose `script-src` allows only same-origin scripts plus the
 *   hashes of the inline scripts in `index.html` (the pre-paint theme script). The hashes are computed from the
 *   built `index.html` (at startup on Node, at build time for `_headers`), so editing the script cannot drift.
 */

export const BASE_SECURITY_HEADERS = {
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'no-referrer',
} as const;

/** One year, including subdomains. No `preload`: that is an irreversible, domain-wide decision for the operator. */
export const HSTS_VALUE = 'max-age=31536000; includeSubDomains';

/**
 * Inline `<script>` bodies (no `src`) of an HTML document, exactly as the browser hashes them for CSP.
 * Only classic/module scripts are returned; JSON/importmap-like data blocks would not need a hash, but a hash for
 * them is harmless, so every inline `<script>` is included.
 */
export function inlineScripts(html: string): string[] {
  const out: string[] = [];
  const re = /<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi;
  for (let m = re.exec(html); m; m = re.exec(html)) {
    if (/\bsrc\s*=/i.test(m[1])) continue;
    out.push(m[2]);
  }
  return out;
}

function toBase64(bytes: ArrayBuffer): string {
  let bin = '';
  for (const b of new Uint8Array(bytes)) bin += String.fromCharCode(b);
  return btoa(bin);
}

/** CSP source expressions (`'sha256-…'`) for every inline script in `html`. */
export async function inlineScriptHashes(html: string): Promise<string[]> {
  const enc = new TextEncoder();
  const hashes = await Promise.all(inlineScripts(html).map(async (s) => `'sha256-${toBase64(await crypto.subtle.digest('SHA-256', enc.encode(s)))}'`));
  return [...new Set(hashes)];
}

/**
 * The SPA's Content-Security-Policy.
 * - scripts: same origin + the inline-script hashes (no `unsafe-inline`, no `unsafe-eval`);
 * - styles: same origin + Google Fonts CSS; `'unsafe-inline'` because sonner and Radix inject `<style>` elements at
 *   runtime (style injection cannot run script);
 * - images: self, `data:` and `blob:` (vault scans, previews); fonts: self + Google Fonts files;
 * - frames/objects: self + `blob:` for the in-app PDF previews (vault, annexure drafts); the app itself may not be
 *   framed (`frame-ancestors 'none'`, same as `X-Frame-Options: DENY`);
 * - `connect-src 'self'`: the SPA only talks to its own /api.
 */
export function spaCsp(scriptHashes: readonly string[]): string {
  return [
    "default-src 'self'",
    `script-src 'self'${scriptHashes.map((h) => ` ${h}`).join('')}`,
    "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
    "font-src 'self' data: https://fonts.gstatic.com",
    "img-src 'self' data: blob:",
    "connect-src 'self'",
    "frame-src 'self' blob:",
    "object-src 'self' blob:",
    "worker-src 'self' blob:",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; ');
}

/** `spaCsp` for a given `index.html`. */
export async function spaCspFor(html: string): Promise<string> {
  return spaCsp(await inlineScriptHashes(html));
}

/**
 * Cloudflare static-assets `_headers` file content: the same headers for every asset path (HTML gets the CSP; the
 * CSP is harmless on JS/CSS/images). Static assets are only served over https in production, so HSTS is included.
 */
export function cloudflareHeadersFile(csp: string): string {
  const lines = ['/*'];
  for (const [k, v] of Object.entries(BASE_SECURITY_HEADERS)) lines.push(`  ${k}: ${v}`);
  lines.push(`  Strict-Transport-Security: ${HSTS_VALUE}`);
  lines.push(`  Content-Security-Policy: ${csp}`);
  return `# Generated by apps/web/vite.config.ts from dist/index.html (002/FR-050). Do not edit.\n${lines.join('\n')}\n`;
}
